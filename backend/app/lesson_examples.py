"""On-demand, disk-cached real-world examples for curriculum lessons.

The syllabus holds ~48,000 lessons whose reading text only *asks* students to
find a real-world example. Rather than shipping tens of thousands of
hand-written paragraphs, the example is generated by the AI tutor the first
time a lesson asks for it and cached, so every later request is free.
"""
import hashlib
import json
import time
from pathlib import Path

from fastapi import APIRouter, HTTPException

from app import ai_tutor

router = APIRouter(prefix="/api/lesson-example", tags=["lessons"])

CACHE_DIR = Path(__file__).resolve().parent.parent / "data" / "lesson_examples"


def _cache_path(lesson_id: str, title: str, subject: str, level: str) -> Path:
    key = "|".join((lesson_id, title, subject, level)).lower()
    return CACHE_DIR / f"{hashlib.sha1(key.encode('utf-8')).hexdigest()}.json"


@router.get("")
def lesson_example(
    title: str,
    subject: str = "",
    lesson_id: str = "",
    level: str = "",
    grade: int = 1,
    summary: str = "",
    concepts: str = "",
):
    title, subject, level = title.strip()[:200], subject.strip()[:100], level.strip()[:20]
    if len(title) < 2:
        raise HTTPException(status_code=400, detail="title is required")
    path = _cache_path(lesson_id.strip()[:100], title, subject, level)
    if path.exists():
        try:
            return {"example": json.loads(path.read_text(encoding="utf-8"))["example"], "cached": True}
        except (OSError, ValueError, KeyError):
            pass
    key_concepts = [c.strip() for c in concepts.split(",") if c.strip()][:8]
    example = ai_tutor.generate_real_world_example(
        title, subject, grade=grade, level=level or None, key_concepts=key_concepts, summary=summary,
    )
    if not example:
        return {"example": None, "cached": False, "unavailable": True}
    try:
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({"example": example, "created_at": time.time()}), encoding="utf-8")
    except OSError:
        pass
    return {"example": example, "cached": False}
