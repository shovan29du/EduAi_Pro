def google_maps_url(lat, lng):
    return f"https://www.google.com/maps/@{lat},{lng},12z"


def google_earth_url(lat, lng):
    # A wide-ish altitude (20000m) with a straight-down view gives a nice
    # "arriving from orbit" framing for a virtual tour without requiring an API key.
    return f"https://earth.google.com/web/@{lat},{lng},0a,20000d,35y,0h,0t,0r"


def main():
    data = json.loads(DATA_PATH.read_text())
    countries = data["countries"]

    missing = [c["code"] for c in countries if c["code"] not in CAPITAL_COORDS]
    if missing:
        raise SystemExit(f"Missing capital coordinates for: {missing}")

    updated = 0
    for c in countries:
        lat, lng = CAPITAL_COORDS[c["code"]]
        c["coordinates"] = {"lat": lat, "lng": lng}
        c.setdefault("links", {})
        c["links"]["google_maps"] = google_maps_url(lat, lng)
        c["links"]["google_earth"] = google_earth_url(lat, lng)
        updated += 1

    DATA_PATH.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    print(f"Added coordinates + Google Maps/Earth links to {updated} countries.")


if __name__ == "__main__":
    main()
